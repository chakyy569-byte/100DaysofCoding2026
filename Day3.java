public class Day3 {
    public static void main(String[] args) {
        /*
         * penggunaan (\n)
         * fungsinya yaitu untuk membuat baris baru
         */
        System.out.println("Halo\nNama Saya Zaky");
        /*
         * penggunaan (\t)
         * fungsinya yaitu untuk membuat jarak
         */
        System.out.println("umur :\t18");
        System.out.println("hobi :\tmain game dan memasak");
        /*
         * penggunaan (\\)
         * fungsinya yaitu untuk menampilkan backslash
         */
        System.out.println("kata-kata untuk hari ini : \"jangan lupa bahagia\"");
	
}
    
}
